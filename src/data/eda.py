"""Exploratory data analysis of a merged YOLO dataset: balance, box geometry, label quality.

Answers the questions that drive modelling decisions:
  * class / source balance per split, background share, objects per image
  * box size and aspect ratio per class, and the distance range that box size implies
    (pinhole model, configs/camera.yaml), i.e. which distances the model is trained for
  * where boxes sit in the image (centre heatmaps)
  * label quality: duplicate boxes, boxes cut by the image border, tiny boxes
  * image resolutions and a sample grid per class for a visual sanity check

Usage:
    python src/data/eda.py --data data/merged_v3
Writes results/eda/*.png and results/eda/summary.md
"""

import argparse
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path

import cv2
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from distance import DistanceEstimator  # noqa: E402

CLASSES = ["cone", "barrier", "stop_sign"]
COLORS = ["#f28e2b", "#edc948", "#e15759"]
EDGE = 0.002  # a box side within this (normalized) of the border counts as cut off


def load(split_dir: Path) -> list[dict]:
    """One record per image: path, source, size, boxes as (cls, cx, cy, w, h) normalized."""
    records = []
    for img in sorted((split_dir / "images").iterdir()):
        lbl = split_dir / "labels" / (img.stem + ".txt")
        boxes = [tuple(float(v) for v in line.split()) for line in lbl.read_text().splitlines() if line.strip()]
        with Image.open(img) as im:
            size = im.size
        records.append({"path": img, "source": img.name.split("__")[0], "size": size, "boxes": boxes})
    return records


def iou(a, b) -> float:
    ax1, ay1, ax2, ay2 = a[1] - a[3] / 2, a[2] - a[4] / 2, a[1] + a[3] / 2, a[2] + a[4] / 2
    bx1, by1, bx2, by2 = b[1] - b[3] / 2, b[2] - b[4] / 2, b[1] + b[3] / 2, b[2] + b[4] / 2
    inter = max(0, min(ax2, bx2) - max(ax1, bx1)) * max(0, min(ay2, by2) - max(ay1, by1))
    return inter / (a[3] * a[4] + b[3] * b[4] - inter + 1e-12)


def md_table(header: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return "\n".join(lines + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", type=Path, default=Path("data/merged_v3"))
    parser.add_argument("--out", type=Path, default=Path("results/eda"))
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    splits = {s: load(args.data / s) for s in ("train", "val", "test") if (args.data / s / "images").exists()}
    all_recs = [r for recs in splits.values() for r in recs]
    md = [f"# EDA — `{args.data}`\n", "Generated by `src/data/eda.py`.\n"]

    # 1. balance
    rows = []
    for s, recs in splits.items():
        inst = Counter(CLASSES[int(b[0])] for r in recs for b in r["boxes"])
        bg = sum(not r["boxes"] for r in recs)
        rows.append([s, len(recs), f"{bg} ({100 * bg / len(recs):.0f}%)", *(inst[c] for c in CLASSES)])
    md += ["## 1. Split and class balance\n", md_table(["split", "images", "backgrounds", *CLASSES], rows), ""]

    src_rows = defaultdict(Counter)
    for r in all_recs:
        src_rows[r["source"]]["images"] += 1
        for b in r["boxes"]:
            src_rows[r["source"]][CLASSES[int(b[0])]] += 1
    md += [
        "Instances by source (all splits):\n",
        md_table(
            ["source", "images", *CLASSES], [[k, v["images"], *(v[c] for c in CLASSES)] for k, v in src_rows.items()]
        ),
        "",
    ]

    multi = Counter()
    for r in all_recs:
        multi[len({int(b[0]) for b in r["boxes"]})] += 1
    md += [
        f"Objects per image: median {np.median([len(r['boxes']) for r in all_recs]):.0f}, "
        f"max {max(len(r['boxes']) for r in all_recs)}. Images with 2+ different classes: "
        f"{multi[2] + multi[3]} ({100 * (multi[2] + multi[3]) / len(all_recs):.1f}%).\n"
    ]

    # 2. box geometry
    est = DistanceEstimator.from_config()
    geo = {c: {"ar": [], "hpx": [], "dist": [], "cx": [], "cy": []} for c in CLASSES}
    for r in all_recs:
        W, H = r["size"]
        for c, cx, cy, w, h in r["boxes"]:
            g = geo[CLASSES[int(c)]]
            g["cx"].append(cx)
            g["cy"].append(cy)
            g["ar"].append((w * W) / (h * H))
            # rescale to a 1280-wide frame, the reference camera of the distance model
            s = 1280 / W
            box = (0, 0, w * W * s, h * H * s)
            g["hpx"].append(h * H * s)
            g["dist"].append(est.estimate(CLASSES[int(c)], box, 1280))

    fig, ax = plt.subplots(1, 3, figsize=(15, 4))
    bins = np.logspace(np.log10(5), np.log10(1280), 40)
    for c, col in zip(CLASSES, COLORS, strict=True):
        ax[0].hist(geo[c]["hpx"], bins=bins, alpha=0.6, color=col, label=c)
        ax[1].hist(geo[c]["ar"], bins=np.linspace(0, 3, 40), alpha=0.6, color=col, label=c)
        ax[2].hist(np.clip(geo[c]["dist"], 0, 60), bins=np.linspace(0, 60, 41), alpha=0.6, color=col, label=c)
    ax[0].set(xscale="log", title="Box height (px, rescaled to 1280-wide frame)", xlabel="px")
    ax[1].set(title="Aspect ratio (width / height)", xlabel="w / h")
    ax[2].set(title="Implied distance (pinhole model, clipped at 60 m)", xlabel="m")
    for a in ax:
        a.legend()
    fig.tight_layout()
    fig.savefig(args.out / "box_geometry.png", dpi=110)
    plt.close(fig)

    rows = []
    for c in CLASSES:
        g = geo[c]
        hp, d = np.array(g["hpx"]), np.array(g["dist"])
        rows.append(
            [c, len(hp), f"{np.median(hp):.0f}", f"{100 * np.mean(hp < 32):.0f}%",
             f"{np.median(g['ar']):.2f}", f"{np.percentile(d, 10):.1f} – {np.percentile(d, 90):.1f}"]
        )  # fmt: skip
    md += [
        "## 2. Box geometry\n",
        "![box geometry](box_geometry.png)\n",
        md_table(
            ["class", "boxes", "median height px", "small (<32 px)", "median w/h", "implied distance p10–p90 (m)"], rows
        ),
        "",
    ]

    fig, ax = plt.subplots(1, 3, figsize=(13, 4))
    for a, c in zip(ax, CLASSES, strict=True):
        hm, _, _ = np.histogram2d(geo[c]["cy"], geo[c]["cx"], bins=40, range=[[0, 1], [0, 1]])
        a.imshow(hm, extent=(0, 1, 1, 0), cmap="magma")
        a.set(title=f"{c} box centres", xlabel="x", ylabel="y")
    fig.tight_layout()
    fig.savefig(args.out / "box_centres.png", dpi=110)
    plt.close(fig)
    md += ["![box centres](box_centres.png)\n"]

    # 3. label quality
    dup, cut, tiny = Counter(), Counter(), Counter()
    for r in all_recs:
        bs = r["boxes"]
        for i, b in enumerate(bs):
            c = CLASSES[int(b[0])]
            if any(int(b[0]) == int(o[0]) and iou(b, o) > 0.9 for o in bs[i + 1 :]):
                dup[c] += 1
            if (
                b[1] - b[3] / 2 < EDGE
                or b[2] - b[4] / 2 < EDGE
                or b[1] + b[3] / 2 > 1 - EDGE
                or b[2] + b[4] / 2 > 1 - EDGE
            ):
                cut[c] += 1
            if min(b[3] * r["size"][0], b[4] * r["size"][1]) < 4:
                tiny[c] += 1
    md += [
        "## 3. Label quality\n",
        md_table(
            ["class", "near-duplicate boxes (IoU > 0.9)", "cut by image border", "tiny (< 4 px side)"],
            [[c, dup[c], cut[c], tiny[c]] for c in CLASSES],
        ),
        "",
    ]

    # 4. image sizes
    sizes = Counter(r["size"] for r in all_recs)
    md += [
        "## 4. Image resolutions\n",
        md_table(["width × height", "images"], [[f"{w} × {h}", n] for (w, h), n in sizes.most_common(6)]),
        f"\n{len(sizes)} distinct resolutions in total.\n",
    ]

    # 5. sample grid
    rng = random.Random(args.seed)
    tiles = []
    for ci in range(len(CLASSES)):
        pool = [r for r in splits["train"] if any(int(b[0]) == ci for b in r["boxes"])]
        for r in rng.sample(pool, 6):
            img = cv2.imread(str(r["path"]))
            h, w = img.shape[:2]
            for b in r["boxes"]:
                x1, y1 = int((b[1] - b[3] / 2) * w), int((b[2] - b[4] / 2) * h)
                x2, y2 = int((b[1] + b[3] / 2) * w), int((b[2] + b[4] / 2) * h)
                cv2.rectangle(img, (x1, y1), (x2, y2), (0, 255, 0), max(2, w // 300))
            tiles.append(cv2.resize(img, (240, 180)))
    rows_img = [np.hstack(tiles[i : i + 6]) for i in range(0, len(tiles), 6)]
    cv2.imwrite(str(args.out / "samples.jpg"), np.vstack(rows_img))
    md += ["## 5. Random training samples (rows: cone, barrier, stop sign)\n", "![samples](samples.jpg)\n"]

    (args.out / "summary.md").write_text("\n".join(md))
    print(f"Wrote {args.out}/summary.md")


if __name__ == "__main__":
    main()
